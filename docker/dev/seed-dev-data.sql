-- =============================================================================
-- seed-dev-data.sql - DEVELOPMENT ONLY test data for the KUKA FM Middleware
-- =============================================================================
-- Purpose
--   Fills an EMPTY development database with robots, missions and their history
--   to exercise the UI and API edge cases (all status codes, null values,
--   max-length codes, 100-row history paging boundaries, sort tie-breaks).
--   Never mounted into compose, never copied into images, never used in production.
--   All codes are prefixed SEED- so seeded rows are easy to recognise.
--
-- Run (PowerShell, repo root)
--   1. Start the dev stack (the API creates the schema on startup):
--        docker compose -f docker/docker-compose.yml up -d --build
--   2. Wait until the api log shows the EF migrations were applied
--      (or "No migrations were applied"):
--        docker compose -f docker/docker-compose.yml logs api
--   3. Run the seed:
--        Get-Content docker/dev/seed-dev-data.sql | docker compose -f docker/docker-compose.yml exec -T postgres psql -v ON_ERROR_STOP=1 -U root -d kukafm
--
-- Safety
--   Runs in one transaction. Aborts with an error (nothing written) if any
--   SEED- robot already exists or table "mission" is not empty. Real robots
--   inserted by robot sync do not block the seed. Never truncates or deletes
--   anything.
--
-- Cleanup (seeded rows are not removed by the app)
--   docker compose -f docker/docker-compose.yml down
--   docker volume rm kuka-fm-middleware_postgres-data-Development
--
-- Data rules (system-definition section 5): every history row holds the PREVIOUS
-- state; valid_from = previous updated_at, valid_to = time of the change; periods
-- of one item never overlap; the last history row ends at the item's updated_at;
-- completed_at is set only for final mission statuses (history rows are always
-- previous active states, so their completed_at is null).
-- The id columns are identity columns and are generated by PostgreSQL.
-- =============================================================================

BEGIN;

-- The api keeps running while seeding; the locks block robot sync and mission
-- dispatch writes between the guard and the seed (they wait until COMMIT).
LOCK TABLE robot, mission IN EXCLUSIVE MODE;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM robot WHERE robot_code LIKE 'SEED-%')
       OR EXISTS (SELECT 1 FROM mission) THEN
        RAISE EXCEPTION 'Seed aborted: SEED- robots already exist or table "mission" is not empty. The seed runs only once on a development database without missions (see header for cleanup).';
    END IF;
END $$;

-- -----------------------------------------------------------------------------
-- Mission definitions (120 missions; created before the robots so that robot
-- SEED-R02 can reference the mission it executes).
-- n 1-9 cover all 9 KUKA job statuses and the history counts 0 / 99 / 100 / 101 / 250.
-- Only 5 missions are active, so a running mission sync polls little.
-- -----------------------------------------------------------------------------
CREATE TEMP TABLE seed_mission_def ON COMMIT DROP AS
SELECT
    n,
    'SEED-' || substr(md5('seed-mission-' || n), 1, 27)                      AS mission_code,
    'SEED-' || substr(md5('seed-request-' || n), 1, 27)                      AS request_id,
    'SEED-R0' || (((n - 1) % 8) + 1)                                         AS robot_code,
    'SEED-R0' || ((n % 8) + 1)                                               AS alt_robot_code,
    CASE n
        WHEN 1 THEN 10 WHEN 2 THEN 20 WHEN 3 THEN 31 WHEN 4 THEN 30 WHEN 5 THEN 50
        WHEN 6 THEN 25 WHEN 7 THEN 28 WHEN 8 THEN 35 WHEN 9 THEN 60
        ELSE (ARRAY[30, 31, 35, 60])[(n % 4) + 1]
    END::smallint                                                             AS status,
    CASE WHEN n = 3 THEN 'SEED-START-' || repeat('S', 53)                     -- 64 chars
         ELSE 'SEED-N' || lpad(((n * 7) % 500)::text, 4, '0') END            AS start_node,
    CASE WHEN n = 3 THEN 'SEED-TARGET-' || repeat('T', 52)                    -- 64 chars
         WHEN n = 6 THEN 'SEED-N' || lpad(((n * 7) % 500)::text, 4, '0')     -- start = target
         ELSE 'SEED-N' || lpad(((n * 11) % 500)::text, 4, '0') END           AS target_node,
    -- missions 7 and 8 share created_at (id tie-break in the list sort)
    timestamptz '2026-11-01 08:00:00+00'
        + (CASE WHEN n = 8 THEN 6 ELSE n - 1 END) * interval '10 minutes'    AS created_at,
    CASE n
        WHEN 1 THEN 0 WHEN 2 THEN 99 WHEN 3 THEN 100 WHEN 4 THEN 101 WHEN 5 THEN 250
        WHEN 6 THEN 1 WHEN 7 THEN 2 WHEN 8 THEN 1 WHEN 9 THEN 1
        ELSE 1 + (n % 3)
    END                                                                       AS history_count
FROM generate_series(1, 120) AS n;

CREATE TEMP TABLE seed_mission_status (status smallint PRIMARY KEY, name varchar(32) NOT NULL, is_final boolean NOT NULL) ON COMMIT DROP;
INSERT INTO seed_mission_status (status, name, is_final) VALUES
    (10, 'Created', false), (20, 'Executing', false), (25, 'Waiting', false), (28, 'Cancelling', false),
    (50, 'Warning', false), (30, 'Complete', true), (31, 'Cancelled', true), (35, 'Manual complete', true),
    (60, 'Startup error', true);

CREATE TEMP TABLE seed_robot_status (status smallint PRIMARY KEY, name varchar(32) NOT NULL) ON COMMIT DROP;
INSERT INTO seed_robot_status (status, name) VALUES
    (1, 'Departure'), (2, 'Offline'), (3, 'Idle'), (4, 'Executing'), (5, 'Charging'), (6, 'Updating'), (7, 'Abnormal');

-- -----------------------------------------------------------------------------
-- Robots: statuses 1-7 (Available / Busy / Offline), null type / battery /
-- map / node / mission, battery 0, 100 and 57.35, one 64-char node code.
-- History counts: R01 0, R02 1, R03 100, R04 101, R05 250, R06-R08 0.
-- R04: history rows 1 and 2 share valid_to (positions 101 and 100 newest first,
-- i.e. the tie straddles the first history page boundary; id decides the order).
-- -----------------------------------------------------------------------------
CREATE TEMP TABLE seed_robot_def (
    robot_code varchar(32), robot_type varchar(32), status smallint, battery_level numeric(5,2),
    map_code varchar(32), node_code varchar(64), mission_code varchar(32), history_count int, valid_to_tie boolean
) ON COMMIT DROP;
INSERT INTO seed_robot_def (robot_code, robot_type, status, battery_level, map_code, node_code, mission_code, history_count, valid_to_tie) VALUES
    ('SEED-R01', 'KMP600I', 3, 100.00, 'SEED-MAP-A', 'SEED-NODE-0001', NULL, 0, false),
    ('SEED-R02', 'KMP600I', 4, 57.35, 'SEED-MAP-A', 'SEED-NODE-0002',
        (SELECT mission_code FROM seed_mission_def WHERE n = 2), 1, false),
    ('SEED-R03', NULL, 2, NULL, NULL, NULL, NULL, 100, false),
    ('SEED-R04', 'KMP1500', 1, 0.00, 'SEED-MAP-B', 'SEED-NODE-' || repeat('L', 54), NULL, 101, true),  -- 64-char node
    ('SEED-R05', 'KMP600I', 5, 12.50, 'SEED-MAP-A', 'SEED-NODE-0005', NULL, 250, false),
    ('SEED-R06', 'KMP1500', 6, 88.00, 'SEED-MAP-B', NULL, NULL, 0, false),
    ('SEED-R07', NULL, 7, 33.33, 'SEED-MAP-A', 'SEED-NODE-0007', NULL, 0, false),
    ('SEED-R08', 'KMP600I', 3, NULL, 'SEED-MAP-B', 'SEED-NODE-0008', NULL, 0, false);

-- Change k of a robot happens at t0 + step(k) * 30 s; with the tie, changes 1 and 2 happen at the same time.
CREATE TEMP TABLE seed_robot_hist ON COMMIT DROP AS
SELECT d.robot_code, d.robot_type, d.map_code, i,
       ((i - 1) % 7 + 1)::smallint                                AS status,
       ((i * 37) % 10000) / 100.0                                 AS battery_level,
       'SEED-NODE-H' || lpad(i::text, 4, '0')                     AS node_code,
       timestamptz '2026-11-01 06:00:00+00'
           + (i - 1 - CASE WHEN d.valid_to_tie AND i >= 3 THEN 1 ELSE 0 END) * interval '30 seconds' AS valid_from,
       timestamptz '2026-11-01 06:00:00+00'
           + (i - CASE WHEN d.valid_to_tie AND i >= 2 THEN 1 ELSE 0 END) * interval '30 seconds'     AS valid_to
FROM seed_robot_def d
CROSS JOIN LATERAL generate_series(1, d.history_count) AS i;

INSERT INTO robot (robot_code, robot_type, status, status_name, battery_level, map_code, node_code, mission_code, updated_at)
SELECT d.robot_code, d.robot_type, d.status, s.name, d.battery_level, d.map_code, d.node_code, d.mission_code,
       COALESCE((SELECT max(h.valid_to) FROM seed_robot_hist h WHERE h.robot_code = d.robot_code),
                timestamptz '2026-11-01 06:00:00+00')
FROM seed_robot_def d
JOIN seed_robot_status s ON s.status = d.status
ORDER BY d.robot_code;

INSERT INTO robot_status_history (robot_id, robot_code, robot_type, status, status_name, battery_level, map_code, node_code, mission_code, valid_from, valid_to)
SELECT r.id, h.robot_code, h.robot_type, h.status, s.name, h.battery_level, h.map_code, h.node_code, NULL, h.valid_from, h.valid_to
FROM seed_robot_hist h
JOIN robot r ON r.robot_code = h.robot_code
JOIN seed_robot_status s ON s.status = h.status
ORDER BY h.robot_code, h.i;

-- -----------------------------------------------------------------------------
-- Mission history: row 1 is the initial Created (10) state, later rows cycle
-- 20 / 25 / 50; for missions with >= 10 rows the robot alternates every 10 rows
-- (robot changed). Change j happens at created_at + j * 5 s.
-- -----------------------------------------------------------------------------
CREATE TEMP TABLE seed_mission_hist ON COMMIT DROP AS
SELECT d.n, j,
       CASE WHEN j = 1 THEN 10 ELSE (ARRAY[20, 25, 50])[((j - 2) % 3) + 1] END::smallint AS status,
       CASE WHEN d.history_count >= 10 AND (j / 10) % 2 = 1 THEN d.alt_robot_code ELSE d.robot_code END AS robot_code,
       d.created_at + (j - 1) * interval '5 seconds' AS valid_from,
       d.created_at + j * interval '5 seconds'       AS valid_to
FROM seed_mission_def d
CROSS JOIN LATERAL generate_series(1, d.history_count) AS j;

INSERT INTO mission (mission_code, request_id, mission_type, start_node, target_node, robot_id, status, status_name, created_at, updated_at, completed_at)
SELECT d.mission_code, d.request_id, 'RACK_MOVE', d.start_node, d.target_node, r.id, d.status, s.name, d.created_at,
       d.created_at + d.history_count * interval '5 seconds',
       CASE WHEN s.is_final THEN d.created_at + d.history_count * interval '5 seconds' END
FROM seed_mission_def d
JOIN robot r ON r.robot_code = d.robot_code
JOIN seed_mission_status s ON s.status = d.status
ORDER BY d.n;

INSERT INTO mission_status_history (mission_id, robot_id, mission_code, request_id, mission_type, start_node, target_node, status, status_name, created_at, completed_at, valid_from, valid_to)
SELECT m.id, r.id, d.mission_code, d.request_id, 'RACK_MOVE', d.start_node, d.target_node, h.status, s.name, d.created_at, NULL, h.valid_from, h.valid_to
FROM seed_mission_hist h
JOIN seed_mission_def d ON d.n = h.n
JOIN mission m ON m.mission_code = d.mission_code
JOIN robot r ON r.robot_code = h.robot_code
JOIN seed_mission_status s ON s.status = h.status
ORDER BY h.n, h.j;

COMMIT;
